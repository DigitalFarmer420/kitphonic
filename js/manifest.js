// Builds audio/manifest.json content from content.js (pure; tools/build-manifest.mjs writes it).
// Entry: { id, kind, text (what the clip must say, for the voice actor), tts (placeholder speech text),
//          take (path under audio/ once recorded, else null), placeholder ('tts' | file path), notes? }
import { LETTERS, STRETCHY } from './core.js';
import { LETTER_INFO, WORDS, STAR_WORDS, MASCOT, SFX } from './content.js';
import { requiredClips, protoRimes } from './word-logic.js';

export const TAKE_EXTS = ['m4a', 'mp3', 'ogg', 'wav'];

export function buildManifest(takeFiles = []) {
  const takes = new Map();
  for (const f of takeFiles) { const m = f.match(/^(.+)\.(\w+)$/); if (m && TAKE_EXTS.includes(m[2].toLowerCase())) takes.set(m[1], f); }
  const clips = [];
  const add = (id, kind, text, tts, extra = {}) => clips.push({ id, kind, text, tts, take: takes.has(id) ? `takes/${takes.get(id)}` : null, placeholder: 'tts', ...extra });

  for (const l of LETTERS) {
    const L = LETTER_INFO[l];
    add(`name-${l}`, 'letter-name', L.name, L.nameTts);
    add(`snd-${l}`, 'letter-sound', `/${L.sound}/`, L.soundTts, { notes: STRETCHY.has(l) ? 'short, clean' : 'clipped: quick, no trailing "uh"' });
    if (STRETCHY.has(l)) add(`snd-${l}-held`, 'letter-sound-held', `/${L.sound}/ held ~1 s`, L.heldTts, { notes: 'played on a slow slide' });
  }
  for (const r of protoRimes())
    add(`rime-${r}`, 'rime', r, r, { notes: r.endsWith('s') ? 'rime chunk; s may voice as /z/ (is, as)' : 'rime chunk, said as one unit' });
  const seen = new Set();
  for (const [lv, list] of Object.entries(WORDS)) for (const e of list) {
    if (seen.has(e.w)) continue; seen.add(e.w);
    add(`word-${e.w}`, 'word', e.w, e.w, { level: +lv, notes: 'blended smoothly at the end of a sweep' });
    add(`reveal-${e.w}`, 'reveal', e.say, e.say, { level: +lv, picture: !!e.pic });
  }
  for (const s of STAR_WORDS) {
    add(`star-${s.w}`, 'star-word', s.w, s.w, { tricky: s.tricky });
    add(`star-${s.w}-sentence`, 'star-sentence', s.say, s.say);
  }
  for (const [id, text] of Object.entries(MASCOT)) add(id, 'mascot', text, text.replace('…', ''), { voice: id.endsWith('-upbeat') ? 'upbeat' : 'calm' });
  for (const [id, s] of Object.entries(SFX)) add(id, 'sfx', s.text, null, { placeholder: s.file });

  const missing = [...requiredClips()].filter(id => !clips.some(c => c.id === id));
  if (missing.length) throw new Error('manifest missing clips: ' + missing.join(', '));
  return {
    version: 1,
    note: 'Generated by `npm run manifest` from js/content.js. Drop recorded clips into audio/takes/ named <id>.<ext> (m4a/mp3/ogg/wav) and re-run; `take` fills in automatically. Until then the app speaks `tts` with the browser voice (or a soft tone if none).',
    takesDir: 'takes/',
    count: clips.length,
    clips,
  };
}
